#!/usr/bin/env python3
"""Generate native/unicode_data.h: NFKD decompositions and General_Category=Mark ranges."""
import unicodedata

MAX = 0x110000
decomp = []
marks = []
start = None
for cp in range(MAX):
    cat = unicodedata.category(chr(cp))
    is_mark = cat.startswith('M')
    if is_mark:
        if start is None:
            start = cp
    else:
        if start is not None:
            marks.append((start, cp - 1))
            start = None
    if 0xD800 <= cp <= 0xDFFF:
        continue
    seq = unicodedata.normalize('NFKD', chr(cp))
    if seq != chr(cp):
        decomp.append((cp, [ord(c) for c in seq]))
if start is not None:
    marks.append((start, MAX - 1))

seqs = []
entries = []
off = 0
for cp, ds in decomp:
    entries.append((cp, off, len(ds)))
    seqs.extend(ds)
    off += len(ds)

with open('unicode_data.h', 'w') as f:
    f.write('// Generated by tools/gen_unicode.py from Python unicodedata %s. Do not edit.\n' % unicodedata.unidata_version)
    f.write('#pragma once\n#include <cstdint>\n\n')
    f.write('struct NfkdEntry { uint32_t cp; uint32_t off; uint8_t len; uint8_t pad[3]; };\n')
    f.write('static const uint32_t kSeq[] = {\n')
    for i in range(0, len(seqs), 16):
        f.write(','.join('0x%X' % x for x in seqs[i:i+16]) + ',\n')
    f.write('};\n\n')
    f.write('static const NfkdEntry kNfkd[] = {\n')
    for cp, o, l in entries:
        f.write('{0x%X,%d,%d},\n' % (cp, o, l))
    f.write('};\n')
    f.write('static const uint32_t kNfkdCount = %d;\n\n' % len(entries))
    f.write('struct MarkRange { uint32_t lo, hi; };\n')
    f.write('static const MarkRange kMarks[] = {\n')
    for lo, hi in marks:
        f.write('{0x%X,0x%X},\n' % (lo, hi))
    f.write('};\n')
    f.write('static const uint32_t kMarkCount = %d;\n' % len(marks))
print('decomp', len(entries), 'seq', len(seqs), 'marks', len(marks))
